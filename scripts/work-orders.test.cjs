const {test} = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs/promises');
const express = require('express');
const register = require('../work-orders-api');
const dates = require('../apps/work-orders/schedule');
const {removeTemporaryDirectory,launchBrowser} = require('./lib/browser-check.cjs');
test('monthly recurrence preserves anchors across short months',()=>{
  assert.equal(dates.plantDate(new Date('2026-11-21T06:30:00Z')),'2026-11-20');
  assert.equal(dates.plantDate(new Date('2026-11-21T07:30:00Z')),'2026-11-21');
  const rule={start:'2028-01-31',interval:1,unit:'months'};
  assert.equal(dates.advance(rule,'2028-02-29'),'2028-03-31');
  assert.equal(dates.advance({...rule,pattern:'first-weekday'},'2028-03-01'),'2028-04-03');
  assert.equal(dates.advance({...rule,start:'2028-01-11',pattern:'ordinal'},'2028-01-11'),'2028-02-08');
});
test('shared directory, roster-free groups, issuing, frozen documents, closeout and print sheets',async t=>{
  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'wo-check-'));
  t.after(()=>removeTemporaryDirectory(directory));
  const app=express();app.use(express.json());
  const operationsDirectory=require('../plant-rounds-api')(app,{directory:path.join(directory,'users')});
  register(app,{directory,operationsDirectory,runTimer:false,sopDirectory:directory});
  app.use('/work-orders',express.static(path.resolve('apps/work-orders')));
  app.use('/apps/sop-creator',express.static(path.resolve('apps/sop-creator')));
  app.use('/shared',express.static(path.resolve('shared')));
  app.get('/api/sops',(req,res)=>res.json([]));
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  t.after(()=>new Promise(resolve=>{server.closeAllConnections();server.close(resolve);}));
  const origin='http://127.0.0.1:'+server.address().port, api=origin+'/api/work-orders';
  const today=dates.plantDate();
  let db=await (await fetch(api)).json();
  const [user,second]=await operationsDirectory();
  async function write(data,status=200){
    const res=await fetch(api,{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({revision:db.revision,...data})});
    const result=await res.json();assert.equal(res.status,status,JSON.stringify(result));if(res.ok)db=result;
  }
  assert.equal(db.groups[0].kind,'shift');assert.deepEqual(db.groups[0].members,[]);
  await write({action:'groups',name:'Instrument crew',kind:'members',members:[user.id,second.id]});
  await write({action:'locations',name:'Gallery'});
  const location=db.locations[0].id;
  await write({action:'locations',name:'North',parent:location});
  await write({action:'locations',id:location,name:'Gallery',parent:db.locations[1].id},400);
  for(const name of ['Analyzer 01','Analyzer 02'])await write({action:'equipment',name,location:db.locations[1].id});
  const bytes=Buffer.from('test document');
  const upload=await fetch(api+'/files?name=manual.pdf',{method:'POST',headers:{Origin:origin,'Content-Type':'application/octet-stream'},body:bytes});
  assert.equal(upload.status,200);const file=await upload.json();
  assert.deepEqual(Buffer.from(await (await fetch(api+'/files/'+file.id)).arrayBuffer()),bytes);
  await write({action:'tasks',name:'Calibrate',instructions:'See manual.',files:[file.id]});
  const plan={action:'plan',task:db.tasks[0].id,assets:db.equipment.map(a=>a.id),start:today,mode:'completion',interval:30,unit:'days',assigned:'group/day-shift',priority:'Routine'};
  await write(plan);assert.equal(db.orders.length,2);assert.equal(db.orders[0].location,'Gallery › North');
  await write({action:'issue',through:dates.days(today,60)});assert.equal(db.orders.length,2);
  const id=db.orders[0].id;
  await write({action:'claim',id,user:user.id});
  await write({action:'complete',id,workers:[],enteredBy:user.id,date:today},400);
  await write({action:'complete',id,workers:[second.id],enteredBy:user.id,date:today,notes:'Verified'});
  assert.equal(db.orders[0].completion.workers[0].name,second.name);
  assert.equal(db.orders[1].completion,null);assert.equal(db.orders[1].assigned,'group/day-shift');
  assert.equal(db.schedules[0].next,dates.days(today,30));
  await write({action:'tasks',id:plan.task,name:'Calibrate',instructions:'New instructions'});
  assert.deepEqual(db.orders[0].files,[file.id]);assert.equal(db.orders[0].instructions,'See manual.');
  await write({action:'issue',through:dates.days(today,60),revision:0},409);
  await write({action:'issue',through:dates.days(today,60)});assert.equal(db.orders.length,3);
  if(process.env.WO_BROWSER==='1'){
    await write({action:'locations',name:'Annex'});
    await write({action:'locations',name:'Bay 10',parent:location});
    await write({action:'locations',name:'Bay 2',parent:location});
    await write({action:'locations',name:'Bench',parent:db.locations[1].id});
    const chrome=await launchBrowser();t.after(()=>chrome.close());
    await chrome.call('Page.navigate',{url:origin+'/work-orders/'});
    for(let i=0;i<100 && !await chrome.evaluate('!!document.querySelector("#rows")');i++)await new Promise(r=>setTimeout(r,50));
    assert.match(await chrome.evaluate('document.getElementById("rows").innerText'),/Day Shift/);
    await chrome.evaluate("document.querySelector('[data-tab=locations]').click()");
    const labels=await chrome.evaluate("Array.from(document.querySelectorAll('.location-name'),el=>[el.textContent,parseFloat(getComputedStyle(el).paddingInlineStart)])");
    assert.deepEqual(labels.map(([name])=>name),['Annex','Gallery','Bay 2','Bay 10','North','Bench']);
    const indents=labels.map(([,indent])=>indent);
    assert.equal(indents[0],0);
    assert.equal(indents[1],0);
    assert.ok(indents[2]>0 && indents[5]>indents[4]);
    await chrome.evaluate("action('plan','')");
    assert.equal(await chrome.evaluate("document.getElementById('editor').open"),true);
    await chrome.evaluate("document.getElementById('close').click(); document.querySelector('[data-tab=groups]').click(); action('edit','')");
    assert.equal(await chrome.evaluate("document.getElementById('member-field').hidden"),true);
    await chrome.evaluate("document.querySelector('select[name=kind]').value='members'; conditional()");
    assert.equal(await chrome.evaluate("document.getElementById('member-field').hidden"),false);
    await chrome.evaluate("document.querySelector('#fields [name=name]').value='Test rotating crew';document.querySelector('[name=members] option').selected=true;document.getElementById('entry').requestSubmit()");
    for(let i=0;i<100 && await chrome.evaluate("document.getElementById('editor').open");i++)await new Promise(r=>setTimeout(r,50));
    assert.match(await chrome.evaluate("document.getElementById('view').textContent"),/Test rotating crew/);
    await chrome.evaluate("window.print=()=>{};action('print-one','"+id+"')");
    assert.match(await chrome.evaluate("document.getElementById('print').textContent"),/Verified/);
    await chrome.evaluate("document.querySelector('[data-tab=orders]').click();action('print-list','')");
    assert.match(await chrome.evaluate("document.getElementById('print').textContent"),/Day Shift/);
    await chrome.call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
    assert.ok(await chrome.evaluate('document.documentElement.scrollWidth<=innerWidth'));
    assert.deepEqual(chrome.errors,[]);
  }
});
